/**
 * Как показать привязанную карту человеку: «•••• 4242 · MIR».
 *
 * Согласие № 2 обещает называть платёжное средство, которым будут списывать,
 * — маской и платёжной системой. Полного номера у нас нет и быть не должно.
 *
 * Возвращает null, когда маски нет: у старых подписок она не сохранялась,
 * а ЮKassa не присылает её для некарточных способов оплаты.
 */
export function formatCard(
  last4: string | null | undefined,
  network: string | null | undefined
): string | null {
  if (!last4) return null;
  return network ? `•••• ${last4} · ${network}` : `•••• ${last4}`;
}
